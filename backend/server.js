const express = require('express');
const cors = require('cors');
const cropRoutes = require('./routes/cropRoutes');
const marketRoutes = require('./routes/marketRoutes');
const weatherRoutes = require('./routes/weatherRoutes');
const feedbackRoutes = require('./routes/feedbackRoutes');
const { notFound, errorHandler } = require('./middleware/errorHandler');
const app = express();
const PORT = Number(process.env.PORT) || 5000;
const allowedOrigin = process.env.FRONTEND_URL;
app.use(cors({origin: allowedOrigin ? allowedOrigin.split(',').map(s=>s.trim()) : true}));
app.use(express.json({limit:'20kb'}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'KrishiMitra API',timestamp:new Date().toISOString()}));
app.use('/api/crops',cropRoutes);
app.use('/api/market-prices',marketRoutes);
app.use('/api/weather',weatherRoutes);
app.use('/api/feedback',feedbackRoutes);
app.use(notFound);
app.use(errorHandler);
app.listen(PORT,()=>console.log(`KrishiMitra API running at http://localhost:${PORT}`));
